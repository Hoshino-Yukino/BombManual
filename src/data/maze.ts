// 东/西/南/北是否可走（无墙）
export function canMove(m: Maze, x: number, y: number, dir: 'U' | 'D' | 'L' | 'R'): boolean {
  if (dir === 'R') return x < 5 && m.v[x][y] === 0;
  if (dir === 'L') return x > 0 && m.v[x - 1][y] === 0;
  if (dir === 'D') return y < 5 && m.h[x][y] === 0;
  /* U */ return y > 0 && m.h[x][y - 1] === 0;
}

// 按两个圆圈位置（无序）匹配迷宫，返回索引或 -1
export function findMaze(a: [number, number], b: [number, number]): number {
  const key = (p: [number, number]) => `${p[0]},${p[1]}`;
  const want = new Set([key(a), key(b)]);
  return MAZES.findIndex((m) => {
    const s = new Set(m.markers.map(key));
    return s.size === want.size && [...want].every((k) => s.has(k));
  });
}

// BFS 最短路径，返回方向序列；无解返回 null
export function solveMaze(
  m: Maze,
  start: [number, number],
  goal: [number, number],
): ('U' | 'D' | 'L' | 'R')[] | null {
  const dirs: ('U' | 'D' | 'L' | 'R')[] = ['U', 'D', 'L', 'R'];
  const delta = { U: [0, -1], D: [0, 1], L: [-1, 0], R: [1, 0] } as const;
  const seen = new Set<string>([`${start[0]},${start[1]}`]);
  const q: { x: number; y: number; path: ('U' | 'D' | 'L' | 'R')[] }[] = [
    { x: start[0], y: start[1], path: [] },
  ];
  while (q.length) {
    const { x, y, path } = q.shift()!;
    if (x === goal[0] && y === goal[1]) return path;
    for (const d of dirs) {
      if (!canMove(m, x, y, d)) continue;
      const nx = x + delta[d][0];
      const ny = y + delta[d][1];
      const k = `${nx},${ny}`;
      if (seen.has(k)) continue;
      seen.add(k);
      q.push({ x: nx, y: ny, path: [...path, d] });
    }
  }
  return null;
}
